async def main() -> None:
    await retriever.rebuild()
    hits_count = 0
    badcases: list[str] = []
    for q, city, expect_kw in CASES:
        results = await retriever.retrieve(q, city=city or None, topk=5)
        joined = " ".join(r["text"] + " " + r["title"] for r in results)
        ok = any(kw in joined for kw in expect_kw)
        hits_count += int(ok)
        if not ok:
            badcases.append(f"  MISS: {q} (期望 {expect_kw})")
    total = len(CASES)
    print(f"评测集 {total} 条，recall@5 = {hits_count}/{total} = {hits_count/total:.1%}")
    if badcases:
        print("badcase：")
        print("\n".join(badcases))


if __name__ == "__main__":
    asyncio.run(main())
